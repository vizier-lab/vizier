-- Workspaces (specs/053-workspace-channel data-model.md). The same shape as the SQLite
-- `init_workspace_schema`.

CREATE TABLE workspace (
    id             TEXT COLLATE "C" PRIMARY KEY,
    name           TEXT NOT NULL,
    name_key       TEXT COLLATE "C" NOT NULL UNIQUE,
    created_by     TEXT NOT NULL,
    stopped_at_seq BIGINT NOT NULL DEFAULT 0,
    created_at     BIGINT NOT NULL,
    updated_at     BIGINT NOT NULL
);

CREATE TABLE workspace_topic (
    id           TEXT COLLATE "C" PRIMARY KEY,
    workspace_id TEXT COLLATE "C" NOT NULL REFERENCES workspace(id) ON DELETE CASCADE,
    name         TEXT NOT NULL,
    name_key     TEXT COLLATE "C" NOT NULL,
    created_by   TEXT NOT NULL,
    created_at   BIGINT NOT NULL,
    UNIQUE (workspace_id, name_key)
);

CREATE TABLE workspace_member (
    workspace_id TEXT COLLATE "C" NOT NULL REFERENCES workspace(id) ON DELETE CASCADE,
    kind         TEXT COLLATE "C" NOT NULL CHECK (kind IN ('person', 'agent')),
    handle       TEXT COLLATE "C" NOT NULL,
    role         TEXT COLLATE "C" NOT NULL CHECK (role IN ('owner', 'member')),
    added_by     TEXT NOT NULL,
    added_at     BIGINT NOT NULL,
    PRIMARY KEY (workspace_id, kind, handle),
    UNIQUE (workspace_id, handle)
);
CREATE INDEX idx_workspace_member_handle ON workspace_member(kind, handle);

CREATE TABLE workspace_entry (
    seq              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id     TEXT COLLATE "C" NOT NULL REFERENCES workspace(id) ON DELETE CASCADE,
    topic_id         TEXT COLLATE "C" NOT NULL REFERENCES workspace_topic(id) ON DELETE CASCADE,
    kind             TEXT COLLATE "C" NOT NULL CHECK (kind IN ('person', 'agent', 'note')),
    author_kind      TEXT COLLATE "C" NOT NULL,
    author           TEXT COLLATE "C" NOT NULL,
    author_name      TEXT NOT NULL,
    body             TEXT NOT NULL,
    files            TEXT,
    history_uid      TEXT COLLATE "C",
    source_session   TEXT COLLATE "C",
    origin           TEXT,
    is_final         BIGINT NOT NULL DEFAULT 0,
    activated_by_seq BIGINT,
    at               BIGINT NOT NULL
);
CREATE INDEX idx_workspace_entry_topic ON workspace_entry(topic_id, seq);

CREATE TABLE workspace_mention (
    entry_seq   BIGINT NOT NULL REFERENCES workspace_entry(seq) ON DELETE CASCADE,
    target_kind TEXT COLLATE "C" NOT NULL,
    target      TEXT COLLATE "C" NOT NULL,
    state       TEXT COLLATE "C" NOT NULL,
    updated_at  BIGINT NOT NULL,
    PRIMARY KEY (entry_seq, target)
);
CREATE INDEX idx_workspace_mention_state ON workspace_mention(state);

CREATE TABLE workspace_read (
    topic_id TEXT COLLATE "C" NOT NULL REFERENCES workspace_topic(id) ON DELETE CASCADE,
    agent_id TEXT COLLATE "C" NOT NULL,
    read_seq BIGINT NOT NULL,
    PRIMARY KEY (topic_id, agent_id)
);

CREATE INDEX idx_sh_channel_topic_time ON session_history(channel, topic, timestamp);

ALTER TABLE notification ADD COLUMN IF NOT EXISTS workspace_id TEXT COLLATE "C";
ALTER TABLE notification ADD COLUMN IF NOT EXISTS author TEXT COLLATE "C";
CREATE INDEX idx_notification_workspace ON notification(workspace_id, id DESC);
